// @vitest-environment jsdom
import React, { act } from "react";
import { createRoot } from "react-dom/client";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { it, expect, vi } from "vitest";
import TvReleaseConfig from "./TvReleaseConfig";
const mocks = vi.hoisted(() => ({ admin: false, get: vi.fn(), put: vi.fn(), post: vi.fn() }));
vi.mock("@/hooks/usePermission", () => ({ useIsAdmin: () => mocks.admin }));
vi.mock("@/utils/http", () => ({ default: { get: mocks.get, put: mocks.put, post: mocks.post } }));
it("hides from staff and disables the published release with a readback", async () => {
  (globalThis as typeof globalThis & { IS_REACT_ACT_ENVIRONMENT: boolean }).IS_REACT_ACT_ENVIRONMENT = true;
  const release = { versionCode: 7, versionName: "0.5", apkUrl: "https://example.com/a.apk", sha256: "a".repeat(64), sizeBytes: 100 };
  let enabled = true;
  mocks.get.mockImplementation(async () => ({ data: { enabled, release } }));
  mocks.put.mockImplementation(async (_url, body) => { enabled = body.enabled; });
  vi.spyOn(window, "confirm").mockReturnValue(true);
  const node = document.createElement("div"); document.body.appendChild(node);
  const root = createRoot(node); const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  const render = () => React.createElement(QueryClientProvider, { client }, React.createElement(TvReleaseConfig));
  await act(async () => { root.render(render()); });
  expect(node.textContent).toBe(""); expect(mocks.get).not.toHaveBeenCalled();
  mocks.admin = true;
  await act(async () => { root.render(render()); await new Promise(r => setTimeout(r, 40)); });
  await act(async () => { await new Promise(r => setTimeout(r, 40)); });
  const button = Array.from(node.querySelectorAll("button")).find(b => b.textContent === "Tắt cập nhật")!;
  await act(async () => { button.click(); await new Promise(r => setTimeout(r, 40)); });
  expect(mocks.put).toHaveBeenCalledWith("/tv-release/admin", { enabled: false, release });
  expect(mocks.get.mock.calls.length).toBeGreaterThan(1);
  await act(async () => { root.unmount(); }); client.clear(); node.remove(); vi.restoreAllMocks();
});
it("uploads the selected APK after confirmation", async () => {
  mocks.admin = true;
  mocks.get.mockImplementation(async (url: string) => ({ data: url.endsWith("/history") ? [] : { enabled: false, release: null } }));
  mocks.post.mockResolvedValue({});
  vi.spyOn(window, "confirm").mockReturnValue(true);
  const node = document.createElement("div"); document.body.appendChild(node);
  const root = createRoot(node); const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  await act(async () => { root.render(React.createElement(QueryClientProvider, { client }, React.createElement(TvReleaseConfig))); await new Promise(r => setTimeout(r, 50)); });
  await act(async () => { await new Promise(r => setTimeout(r, 50)); });
  const input = node.querySelector('input[type=file]') as HTMLInputElement;
  const file = new File(["apk"], "tv.apk", { type: "application/vnd.android.package-archive" });
  Object.defineProperty(input, "files", { value: [file], configurable: true });
  await act(async () => { input.dispatchEvent(new Event("change", { bubbles: true })); });
  const button = Array.from(node.querySelectorAll("button")).find(b => b.textContent === "Kiểm tra và phát hành")!;
  await act(async () => { button.click(); await new Promise(r => setTimeout(r, 30)); });
  expect(mocks.post).toHaveBeenCalledWith("/tv-release/admin/upload", expect.any(FormData), expect.objectContaining({ timeout: 300000 }));
  expect((mocks.post.mock.calls[0][1] as FormData).get("apk")).toBe(file);
  await act(async () => { root.unmount(); }); client.clear(); node.remove(); vi.restoreAllMocks();
});
